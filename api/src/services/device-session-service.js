"use strict";

// ONE ACTIVE SESSION PER ACCOUNT, AND A STEP-UP BEFORE A NEW DEVICE GETS ONE.
//
// What this replaces: nothing. Before this file, TitoPay had no single-session
// rule at all. Every revocation reason in the codebase was account_closed,
// idle_timeout, logout, logout_all, password_reset, refresh_rotated or
// remote_logout - none of them fired on sign-in. A customer could hold an
// unlimited number of live sessions on an unlimited number of devices, each
// good for seven days, and signing in on a new phone left every older session
// fully usable. The admin portal said otherwise. This makes the portal true.
//
// The rule, in the order it runs:
//
//   1. A device that has signed in before is recognised by an id the client
//      stores. It goes straight through.
//   2. A device that has NOT signed in before must pass an OTP, sent to SMS
//      and email together, before any session is issued.
//   3. Once the new device is in, every other session on the account is
//      revoked with reason 'signed_in_on_another_device'.
//   4. The displaced device's next request - or its next token refresh - fails
//      closed and carries that reason, so the app can say WHY it signed out
//      rather than showing a generic expiry.
//   5. The account is told, in the app and by email.
//
// THE FIRST DEVICE ON AN ACCOUNT IS ENROLLED WITHOUT AN OTP, deliberately.
// On the day this ships, no account has ever recorded a device id, so every
// device in existence is "new". Requiring an OTP from all of them at once
// would demand a working SMS and SMTP path for the entire customer base and
// every member of staff simultaneously, and would lock out anybody the OTP
// failed to reach - including the administrators who would have to fix it.
// Enrolling the first device instead means the rule engages from the SECOND
// device onward, per account, which is where it actually does its work. This
// is no weaker than the behaviour it replaces; it is strictly stronger from
// the moment an account has one device on file.
//
// THE KILL SWITCH IS AN ENVIRONMENT VARIABLE, not a database row or a console
// toggle, and that is on purpose: the failure this has to survive is an
// administrator who cannot sign in to reach the console. SINGLE_SESSION=off
// on the API process restores the previous behaviour without a deploy.

const crypto = require("node:crypto");
const { pool } = require("../db/pool");
const { AppError } = require("../lib/errors");

const DISPLACED_REASON = "signed_in_on_another_device";
// The one sentence a displaced device shows. Named here so the API, the app
// and the tests cannot drift apart on the wording of a security notice.
const DISPLACED_MESSAGE = "Your TitoPay account was logged in on another device.";
const DISPLACED_CODE = "session_displaced";

// A device id is generated by the client and is opaque here. It is never a
// credential - knowing one lets nobody in, because the password and, on an
// unrecognised device, the OTP are still required. It only answers "has this
// installation signed in before".
const DEVICE_ID_PATTERN = /^[A-Za-z0-9_-]{16,128}$/;

function normalizeDeviceId(payload = {}) {
  const raw = payload.deviceFingerprint
    || payload.device_fingerprint
    || payload.deviceId
    || payload.device_id
    || "";
  const text = String(raw || "").trim();
  return DEVICE_ID_PATTERN.test(text) ? text : "";
}

// Stored as a hash. The raw id never sits in the database, so a dump of
// trusted_devices cannot be replayed against the login endpoint to make an
// attacker's device look familiar.
function deviceIdHash(deviceId) {
  return crypto.createHash("sha256").update(String(deviceId)).digest("hex");
}

function enforcementEnabled() {
  const value = String(process.env.SINGLE_SESSION ?? "on").trim().toLowerCase();
  return !["off", "false", "0", "no", "disabled"].includes(value);
}

function deviceColumn(userType) {
  return userType === "admin" ? "admin_user_id" : "user_id";
}

let schemaReady = null;
async function ensureDeviceSessionSchema() {
  if (schemaReady) return schemaReady;
  schemaReady = (async () => {
    // sessions.device_fingerprint tells a session which installation it belongs
    // to, so signing in again on the SAME device replaces its own session
    // instead of reporting itself as an intruder.
    await pool.query("ALTER TABLE sessions ADD COLUMN IF NOT EXISTS device_fingerprint TEXT");
    await pool.query("CREATE INDEX IF NOT EXISTS idx_sessions_device ON sessions (user_type, user_id, device_fingerprint)");
    // trusted_devices and its customer index live in schema.sql, and schema.sql
    // is NOT applied at boot - the repo convention is that each service ensures
    // what it needs. Nothing ensured this table, so it was a silent dependency:
    // an installation whose database predates it would have every enrolment
    // fail, and because a failed enrolment cannot fail a sign-in, the whole
    // rule would be off while the sign-in screen looked perfectly normal.
    // (It does exist in production - trustCurrentDevice has used this same
    // ON CONFLICT clause for some time - but relying on that is not the same
    // as guaranteeing it.)
    await pool.query(`
      CREATE TABLE IF NOT EXISTS trusted_devices (
        id UUID PRIMARY KEY,
        user_id UUID REFERENCES users(id) ON DELETE CASCADE,
        admin_user_id UUID REFERENCES admin_users(id) ON DELETE CASCADE,
        device_fingerprint TEXT NOT NULL,
        device_label TEXT NOT NULL DEFAULT 'Trusted device',
        user_agent TEXT,
        ip_address INET,
        metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
        trusted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        last_seen_at TIMESTAMPTZ,
        revoked_at TIMESTAMPTZ,
        CHECK (user_id IS NOT NULL OR admin_user_id IS NOT NULL)
      )
    `);
    // Both ON CONFLICT targets. The customer one is the index rememberDevice
    // and the Security Centre's trustCurrentDevice both infer against; the
    // admin one is new, because staff devices had no unique index at all and
    // would have accumulated a duplicate row per sign-in.
    await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS idx_trusted_devices_user_fingerprint
      ON trusted_devices (user_id, device_fingerprint)
      WHERE user_id IS NOT NULL`);
    await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS idx_trusted_devices_admin_fingerprint
      ON trusted_devices (admin_user_id, device_fingerprint)
      WHERE admin_user_id IS NOT NULL`);
    // Staff have no phone column, so an admin OTP can only reach email today.
    // The column exists so a number can be recorded; nothing requires one.
    await pool.query("ALTER TABLE admin_users ADD COLUMN IF NOT EXISTS phone TEXT");
  })().catch((error) => {
    schemaReady = null;
    throw error;
  });
  return schemaReady;
}

// THIS TABLE HAS TWO WRITERS, AND THEY MUST NOT READ EACH OTHER'S ROWS.
//
// The Security Centre's "trust this device" has always written here too, with
// a fingerprint of `${userAgent}:${ipAddress}` when the client sends none.
// That value is guessable and forgeable - two customers on the same handset
// model behind the same mobile carrier NAT can produce the same string - so
// treating it as proof of which installation is signing in would be a security
// downgrade, not a convenience.
//
// It also breaks the enrolment exemption in the other direction: an account
// that once pressed "trust this device" would count as having a device on
// file, and its owner would be challenged on their next ordinary sign-in
// rather than enrolled quietly.
//
// So rows written by the sign-in path carry a marker, and both reads below
// require it. The Security Centre keeps its own rows and its own list; neither
// feature can be manipulated through the other.
const ENROLMENT_SOURCE = "login_enrolment";
const ENROLLED_BY_LOGIN = `(metadata->>'source') = '${ENROLMENT_SOURCE}'`;

async function isKnownDevice(user, deviceId) {
  if (!deviceId) return false;
  await ensureDeviceSessionSchema();
  const column = deviceColumn(user.user_type);
  const { rowCount } = await pool.query(
    `SELECT 1 FROM trusted_devices
      WHERE ${column} = $1 AND device_fingerprint = $2 AND revoked_at IS NULL
        AND ${ENROLLED_BY_LOGIN}
      LIMIT 1`,
    [user.id, deviceIdHash(deviceId)]
  );
  return rowCount > 0;
}

// Whether this account has EVER signed in from a recorded device. Drives the
// enrolment exemption described at the top of this file, and nothing else.
async function accountHasEnrolledDevice(user) {
  await ensureDeviceSessionSchema();
  const column = deviceColumn(user.user_type);
  const { rowCount } = await pool.query(
    `SELECT 1 FROM trusted_devices
      WHERE ${column} = $1 AND revoked_at IS NULL AND ${ENROLLED_BY_LOGIN}
      LIMIT 1`,
    [user.id]
  );
  return rowCount > 0;
}

async function rememberDevice(user, deviceId, meta = {}) {
  if (!deviceId) return null;
  await ensureDeviceSessionSchema();
  const column = deviceColumn(user.user_type);
  const hash = deviceIdHash(deviceId);
  const label = String(meta.deviceName || "").trim().slice(0, 120) || "TitoPay device";
  const { rows } = await pool.query(
    `INSERT INTO trusted_devices (id, ${column}, device_fingerprint, device_label, user_agent, metadata, last_seen_at)
     VALUES ($1,$2,$3,$4,$5,$6::JSONB,NOW())
     ON CONFLICT (${column}, device_fingerprint) WHERE ${column} IS NOT NULL
     DO UPDATE SET last_seen_at = NOW(), revoked_at = NULL, device_label = EXCLUDED.device_label
     RETURNING id`,
    [
      crypto.randomUUID(),
      user.id,
      hash,
      label,
      String(meta.userAgent || "").slice(0, 400),
      JSON.stringify({ source: ENROLMENT_SOURCE, platform: meta.platform || null })
    ]
  );
  return rows[0]?.id || null;
}

// SIGN EVERY OTHER SESSION OUT.
//
// keepSessionId is the session just issued. Passing it is not optional: the
// new session is written before this runs, so without it the device that just
// signed in would revoke itself and the customer would land on a dead token.
async function revokeOtherSessions(user, { keepSessionId, deviceId = "", reason = DISPLACED_REASON } = {}) {
  await ensureDeviceSessionSchema();
  const { rows } = await pool.query(
    `UPDATE sessions
        SET revoked_at = NOW(), revoked_reason = $3
      WHERE user_type = $1
        AND user_id = $2
        AND revoked_at IS NULL
        AND id <> $4
      RETURNING id, device_name, platform, device_fingerprint, ip_address, created_at`,
    [user.user_type, user.id, reason, keepSessionId]
  );
  if (rows.length) {
    console.info("[single-session] displaced sessions", {
      userType: user.user_type,
      userId: user.id,
      revoked: rows.length,
      // The device id is a client secret of sorts; only whether it was present.
      newDeviceKnown: Boolean(deviceId)
    });
  }
  return rows;
}

// Why a session that no longer works stopped working. Called only on the
// failure path, so the ordinary request does not pay for a second query.
async function describeRevokedSession(sessionId) {
  if (!sessionId) return null;
  const { rows } = await pool.query(
    "SELECT revoked_reason, revoked_at FROM sessions WHERE id = $1 LIMIT 1",
    [sessionId]
  );
  return rows[0] || null;
}

// The 401 a displaced device gets. Its details carry a code so the app can
// show the security sentence instead of a generic "session expired".
function displacedSessionError() {
  return new AppError(401, DISPLACED_MESSAGE, {
    code: DISPLACED_CODE,
    reason: DISPLACED_REASON,
    publicMessage: DISPLACED_MESSAGE
  });
}

async function sessionErrorFor(sessionId, fallbackMessage) {
  const revoked = await describeRevokedSession(sessionId).catch(() => null);
  if (revoked?.revoked_reason === DISPLACED_REASON) return displacedSessionError();
  return new AppError(401, fallbackMessage);
}

// Tests only: forget that the schema was already ensured, so a test can drop a
// table and prove the guard rebuilds it. Nothing in the running API calls this.
function resetDeviceSessionSchemaCache() {
  schemaReady = null;
}

module.exports = {
  resetDeviceSessionSchemaCache,
  DISPLACED_CODE,
  DISPLACED_MESSAGE,
  DISPLACED_REASON,
  accountHasEnrolledDevice,
  deviceIdHash,
  describeRevokedSession,
  displacedSessionError,
  ensureDeviceSessionSchema,
  enforcementEnabled,
  isKnownDevice,
  normalizeDeviceId,
  rememberDevice,
  revokeOtherSessions,
  sessionErrorFor
};
