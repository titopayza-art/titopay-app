<?php
/**
 * First-run installer. Writes app/config.php, creates the tables and the first admin.
 * Once app/config.php exists this file is never reached.
 */
declare(strict_types=1);

session_save_path(STORAGE . '/cache');
session_start();
$errors = [];
$checks = [
    'PHP 8.1 or newer' => version_compare(PHP_VERSION, '8.1.0', '>='),
    'PDO MySQL or SQLite' => extension_loaded('pdo_mysql') || extension_loaded('pdo_sqlite'),
    'cURL' => extension_loaded('curl'),
    'Sodium (encryption)' => extension_loaded('sodium'),
    'mbstring' => extension_loaded('mbstring'),
    'app/ is writable' => is_writable(APP_DIR),
    'storage/ is writable' => is_writable(STORAGE),
    'Composer packages (vendor/)' => is_file(APP_ROOT . '/vendor/autoload.php'),
];

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    if (!hash_equals($_SESSION['install_csrf'] ?? '', (string) ($_POST['_csrf'] ?? ''))) $errors[] = 'Form expired. Try again.';
    $driver = $_POST['driver'] === 'sqlite' ? 'sqlite' : 'mysql';
    $db = $driver === 'sqlite'
        ? ['driver' => 'sqlite', 'path' => STORAGE . '/seageek.sqlite']
        : ['driver' => 'mysql', 'host' => trim($_POST['db_host'] ?: 'localhost'), 'port' => (int) ($_POST['db_port'] ?: 3306), 'name' => trim($_POST['db_name']), 'user' => trim($_POST['db_user']), 'pass' => (string) $_POST['db_pass']];
    $email = strtolower(trim((string) $_POST['email']));
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid admin email.';
    if (mb_strlen((string) $_POST['password']) < 10) $errors[] = 'The admin password needs at least 10 characters.';
    if (!in_array(false, $checks, true) && !$errors) {
        try {
            DB::connect($db);
        } catch (Throwable $e) {
            $errors[] = 'Could not connect to the database: ' . $e->getMessage();
        }
    }
    if (!$errors) {
        $config = [
            'app_url' => rtrim(trim((string) $_POST['app_url']), '/'),
            'app_key' => base64_encode(random_bytes(SODIUM_CRYPTO_SECRETBOX_KEYBYTES)),
            'cron_token' => bin2hex(random_bytes(16)),
            'debug' => false,
            'db' => $db,
        ];
        file_put_contents(APP_DIR . '/config.php', "<?php\n// Generated by the installer on " . gmdate('Y-m-d H:i') . " UTC. Keep app_key safe: stored secrets are encrypted with it.\nreturn " . var_export($config, true) . ";\n");
        @chmod(APP_DIR . '/config.php', 0640);
        config(null, null, true);
        Schema::migrate();
        $house = Desk::house();
        DB::insert('users', ['org_id' => $house['id'], 'name' => trim((string) $_POST['name']) ?: 'Admin', 'email' => $email, 'password_hash' => password_hash((string) $_POST['password'], PASSWORD_DEFAULT), 'role' => 'owner', 'is_admin' => 1, 'email_verified_at' => now(), 'created_at' => now()]);
        Settings::set('support_email', 'hello@seageek.co.za');
        header('Location: ' . $config['app_url'] . '/login?installed=1');
        exit;
    }
}
$_SESSION['install_csrf'] = bin2hex(random_bytes(16));
$guessUrl = ((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http') . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost');
?><!doctype html>
<html lang="en-ZA"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Install SeaGeek</title><link rel="stylesheet" href="/assets/css/app.css"></head>
<body class="auth-body">
<main class="auth-card" style="max-width:560px">
  <h1>Install SeaGeek</h1>
  <p class="muted">This runs once. It writes <code>app/config.php</code>, creates the database tables and your admin account.</p>
  <ul class="checks">
    <?php foreach ($checks as $label => $ok): ?><li class="<?= $ok ? 'ok' : 'bad' ?>"><?= $ok ? '✓' : '✗' ?> <?= htmlspecialchars($label) ?></li><?php endforeach; ?>
  </ul>
  <?php foreach ($errors as $err): ?><div class="alert alert-error"><?= htmlspecialchars($err) ?></div><?php endforeach; ?>
  <form method="post" class="form">
    <input type="hidden" name="_csrf" value="<?= $_SESSION['install_csrf'] ?>">
    <div class="field"><label>Site address</label><input name="app_url" value="<?= htmlspecialchars($_POST['app_url'] ?? $guessUrl) ?>" required></div>
    <div class="field"><label>Database</label>
      <select name="driver" onchange="document.getElementById('mysql').hidden = this.value === 'sqlite'">
        <option value="mysql">MySQL / MariaDB (recommended for production)</option><option value="sqlite">SQLite (testing only)</option>
      </select></div>
    <div id="mysql" class="form">
      <div class="row"><div class="field"><label>Host</label><input name="db_host" value="localhost"></div><div class="field"><label>Port</label><input name="db_port" value="3306"></div></div>
      <div class="field"><label>Database name</label><input name="db_name"></div>
      <div class="row"><div class="field"><label>User</label><input name="db_user"></div><div class="field"><label>Password</label><input name="db_pass" type="password"></div></div>
    </div>
    <h2 style="font-size:18px;margin-top:10px">Admin account</h2>
    <div class="field"><label>Your name</label><input name="name" required></div>
    <div class="field"><label>Email</label><input name="email" type="email" required></div>
    <div class="field"><label>Password (10+ characters)</label><input name="password" type="password" required minlength="10"></div>
    <button class="btn btn-primary" <?= in_array(false, $checks, true) ? 'disabled' : '' ?>>Install</button>
  </form>
</main>
</body></html>
